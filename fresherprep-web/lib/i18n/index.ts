export function useI18n() {
  const locale = useSyncExternalStore<Locale>(subscribe, readLocale, readServerLocale);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dataset.locale = locale;
    window.localStorage.setItem(storageKey, locale);
  }, [locale]);

  const t = useCallback((key: string, values?: Record<string, string | number>) => {
    const template = locale === "vi" ? (vi[key] ?? key) : key;
    if (!values) return template;
    return Object.entries(values).reduce(
      (text, [name, value]) => text.replaceAll(`{{${name}}}`, String(value)),
      template,
    );
  }, [locale]);

  return { locale, t, setLocale };
}

function readLocale(): Locale {
  return window.localStorage.getItem(storageKey) === "en" ? "en" : "vi";
}

function readServerLocale(): Locale {
  return "vi";
}

function subscribe(onStoreChange: () => void) {
  window.addEventListener("storage", onStoreChange);
  window.addEventListener(changeEvent, onStoreChange);
  return () => {
    window.removeEventListener("storage", onStoreChange);
    window.removeEventListener(changeEvent, onStoreChange);
  };
}

function setLocale(locale: Locale) {
  window.localStorage.setItem(storageKey, locale);
  window.dispatchEvent(new Event(changeEvent));
}
